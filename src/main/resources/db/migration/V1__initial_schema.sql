
CREATE TABLE public.users (
                              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              password_hash varchar(255) NOT NULL,
                              user_name varchar(100) NOT NULL,
                              CONSTRAINT uk_k8d0f2n7n88w1a16yhua64onx
                                  UNIQUE (user_name)
);

CREATE TABLE public.players (
                                id bigint PRIMARY KEY,
                                exp bigint NOT NULL,
                                level integer NOT NULL,
                                name varchar(255),
                                agility integer NOT NULL,
                                intelligence integer NOT NULL,
                                perception integer NOT NULL,
                                strength integer NOT NULL,
                                vitality integer NOT NULL,
                                will integer NOT NULL
);

CREATE TABLE public.quests (
                               id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               ai_context varchar(5000),
                               description varchar(1000),
                               end_date date,
                               exp_reward integer NOT NULL,
                               file_reference varchar(500),
                               owner_id bigint,
                               reset_interval varchar(255) NOT NULL,
                               start_date date,
                               stat_reward varchar(255),
                               stat_reward_amount integer,
                               targets json,
                               title varchar(200) NOT NULL,
                               type varchar(255) NOT NULL,
                               CONSTRAINT quests_reset_interval_check
                                   CHECK (reset_interval IN ('DAILY', 'WEEKLY', 'NONE')),
                               CONSTRAINT quests_type_check
                                   CHECK (type IN (
                                                   'DAILY', 'WEEKLY', 'MAIN',
                                                   'EVENT', 'HIDDEN', 'PERSONAL'
                                       ))
);

CREATE TABLE public.player_quests (
                                      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      completed_at timestamp(6),
                                      last_reset_date date NOT NULL,
                                      player_id bigint NOT NULL,
                                      progress json,
                                      quest_id bigint NOT NULL,
                                      status varchar(255) NOT NULL,
                                      CONSTRAINT player_quests_status_check
                                          CHECK (status IN ('LOCKED', 'ACTIVE', 'COMPLETED'))
);
